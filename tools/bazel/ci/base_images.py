#!/usr/bin/env python3
"""Build the source-backed base images and verify their installed provenance."""

import argparse
from functools import partial
import json
from pathlib import Path, PurePosixPath
import platform
import re
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from tools.bazel.ci import artifact_validation as validation
from tools.bazel.ci import bazel_commands, build, command_log, resolution
from tools.bazel.oci import oci_inventory, oci_layout

IMAGES = ("docker-base-trixie", "docker-config-engine-trixie")
GENERATED_NOTICE = "AUTO-GENERATED by tools/bazel/ci/base_images.py. DO NOT EDIT."


def verify_unique_layer_paths(layout):
    """Docker rejects repeated paths inside a layer, including directories."""
    for layer in layout.layers:
        seen = set()
        with tarfile.open(layer, "r|*") as archive:
            for member in archive:
                name = str(PurePosixPath(member.name))
                validation.require(name not in seen,
                                   "OCI layer repeats a path that Docker cannot load: " + name)
                seen.add(name)


def installed_inventory(layout):
    files = {}
    for layer in layout.layers:
        oci_inventory.apply_layer(layer, files)
    return files


def verify_directory_aliases(files):
    aliases = {"bin": "usr/bin", "sbin": "usr/sbin", "lib": "usr/lib", "var/run": "/run"}
    if "lib64" in files:
        aliases["lib64"] = "usr/lib64"
    for name, target in aliases.items():
        item = files.get(name, {})
        validation.require(item.get("kind") == "symlink" and item.get("linkname") == target,
                           "image changed a Debian directory alias: " + name)
        validation.require(not any(path.startswith(name + "/") for path in files),
                           "image installs files through a directory alias: " + name)


def verify_source_files(files, metadata, machine):
    native = {}
    for report in metadata:
        for package in report["source_packages"]:
            for item in package["native_files"]:
                name = item["path"]
                installed = files.get(name, {})
                validation.require(all(installed.get(key) == item[key]
                                       for key in ("sha256", "mode", "uid", "gid")),
                                   "image changed source package file: " + name)
                validation.require(installed.get("elf_machine") == machine,
                                   "source ELF architecture differs: " + name)
                validation.require(name not in native, "two source owners install the same ELF: " + name)
                native[name] = {**installed, "source_package": package["package"]}
    validation.require(native, "image has no source-built native files")
    return native


def verify_editor_commands(files):
    for name in ("editor", "ex", "rview", "vi", "view"):
        for path, target in (("usr/bin/" + name, "/etc/alternatives/" + name),
                             ("etc/alternatives/" + name, "/usr/bin/vim.tiny")):
            item = files.get(path, {})
            validation.require(item.get("kind") == "symlink" and item.get("linkname") == target,
                               "base image changed the vim-tiny command alternative: " + path)


def verify_symbols(native, runtimes, debug_tar, directory):
    """Use the shared verifier, with the source owner's sealed-core exception."""
    symbols = validation.payload(debug_tar)
    machines = {item["elf_machine"] for item in native.values()}
    validation.require(len(machines) == 1 and all(
        item.get("elf_machine") in machines for item in symbols.values() if "elf_machine" in item),
        "source debug ELF architecture differs from the runtime")
    with tempfile.TemporaryDirectory(prefix="base-symbols-", dir=directory) as temporary:
        root = Path(temporary)
        for archive in [*runtimes, debug_tar]:
            # This is verification-only extraction with the standard archive tool.
            subprocess.run(["bsdtar", "-xf", str(archive), "-C", str(root)], check=True)
        sealed = [name for name, item in native.items()
                  if item["source_package"] == "symcrypt-openssl" and
                  re.fullmatch(r"usr/lib/(?:x86_64|aarch64)-linux-gnu/libsymcrypt\.so\.103\.13\.0", name)]
        validation.require(len(sealed) == 1, "expected the reviewed sealed SymCrypt core")
        ordinary = {name: item for name, item in native.items() if name not in sealed}
        pairs, gaps = validation.elf_debug(root, {**ordinary, **symbols}, set())
        validation.require(not gaps, "source-built package lacks debug symbols")
        core = root / sealed[0]
        sections = validation.command(["readelf", "-SW", str(core)])
        validation.require(".debug_info" not in sections and ".gnu_debuglink" not in sections,
                           "sealed core changed after integrity sealing")
        match = re.search(r"Build ID: ([0-9a-f]+)", validation.command(["readelf", "-n", str(core)]))
        validation.require(match is not None, "sealed core has no build ID")
        identifier = match[1]
        debug_path = "usr/lib/debug/.build-id/" + identifier[:2] + "/" + identifier[2:] + ".debug"
        debug = root / debug_path
        validation.require(debug_path in symbols, "sealed core symbols are absent")
        debug_id = re.search(r"Build ID: ([0-9a-f]+)", validation.command(["readelf", "-n", str(debug)]))
        validation.require(debug_id is not None and debug_id[1] == identifier and
                           ".debug_info" in validation.command(["readelf", "-SW", str(debug)]),
                           "sealed core symbols do not match")
        output = validation.command(["gdb", "-nx", "-batch", "-ex", "set debuginfod enabled off",
                                     "-ex", "set debug-file-directory " + str(root / "usr/lib/debug"),
                                     "-ex", "file " + str(core), "-ex", "info line SymCryptModuleMain"])
        validation.require('Line ' in output and '.c' in output, "GDB cannot find sealed-core source lines")
        pairs.append({"path": sealed[0], "build_id": identifier, "debug_path": debug_path,
                      "lookup": "build-id only: upstream integrity-sealed core"})
        validation.require({item["path"] for item in pairs} == set(native), "incomplete source ELF debug coverage")
    return pairs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifacts", required=True, type=Path)
    parser.add_argument("--architecture", choices=("amd64", "arm64"), required=True)
    parser.add_argument("--bazel", default="bazel")
    args = parser.parse_args()
    directory = args.artifacts.resolve()
    directory.mkdir(parents=True, exist_ok=True)
    machine, elf_machine = {"amd64": ("x86_64", 62), "arm64": ("aarch64", 183)}[args.architecture]
    validation.require(platform.machine() == machine and
                       platform.freedesktop_os_release().get("VERSION_CODENAME") == "trixie",
                       "build requires the selected native Debian Trixie runner")
    receipt = {"_generated": GENERATED_NOTICE, "status": "running", "architecture": args.architecture, "commands": []}
    execute = partial(command_log.execute, cwd=ROOT)
    options = ["--jobs=4", "--local_resources=cpu=4", "--local_resources=memory=10000",
               "--platforms=@sonic_build_infra//platforms:" + machine + "_trixie",
               "--host_platform=@sonic_build_infra//platforms:" + machine + "_trixie"]
    try:
        receipt["revision"] = execute(["git", "rev-parse", "HEAD"], directory, receipt, "revision").strip()
        execute(["make", "-f", "tools/bazel/prepare_manifests.mk",
                 "MANIFEST_METADATA=rules/docker-base-trixie.mk rules/docker-config-engine-trixie.mk",
                 "BUILD_WITH_BAZEL_WHEN_AVAILABLE=y", "BLDENV=trixie", "CONFIGURED_PLATFORM=vs",
                 "CONFIGURED_ARCH=" + args.architecture, "INCLUDE_FIPS=y", "DOCKERS_PATH=dockers"],
                directory, receipt, "make-manifests")
        targets = {}
        for image in IMAGES:
            owner = "//dockers/" + image + ":"
            targets.update({image + ".gz": owner + image + ".gz",
                            image + ".debug.tar": owner + image + ".debug_symbols",
                            image + ".source.tar": owner + "source_runtime",
                            image + ".packages.json": owner + "runtime_package_metadata"})
        targets["config-engine.path-normalization.json"] = "//dockers/docker-config-engine-trixie:runtime_path_normalization"
        tests = ["@sonic_build_infra//oci/tests:runtime_packages_test",
                 "@sonic_build_infra//oci/tests:runtime_packages_rule_test",
                 "@sonic_build_infra//oci/tests:installed_packages_test",
                 "@sonic_build_infra//oci/tests:owner_metadata_test",
                 "@sonic_build_infra//oci/tests:installed_packages_rule_test",
                 "@sonic_build_infra//oci/tests:account_layer_test",
                 "//src/sonic-config-engine:sonic_cfggen_cli_test"]
        layouts = ["//dockers/" + image + ":" + image for image in IMAGES]
        receipt["action_audit"] = bazel_commands.audit_targets(
            args.bazel, options, [*targets.values(), *tests, *layouts], workspace=ROOT,
            output=directory / "action-audit.json")
        execute([args.bazel, "test", *options, "--test_output=errors", *tests], directory, receipt, "tests")
        paths = build.collect_archives(ROOT, directory, receipt, targets, bazel=args.bazel, options=options)
        # Cached archives need not materialize their intermediate OCI layouts.
        # Request the directories we inspect; cquery only locates their outputs.
        execute([args.bazel, "build", *options,
                 "--build_event_json_file=" + str(directory / "layout-build-events.jsonl"),
                 *layouts], directory, receipt, "layouts")
        reports, runtimes = [], []
        receipt["images"] = {}
        for image in IMAGES:
            label = "//dockers/" + image + ":" + image
            output = execute([args.bazel, "cquery", *options, "--output=files", label],
                             directory, receipt, image + ".layout").strip()
            layout = oci_layout.validate_layout(ROOT / output, "linux/" + args.architecture)
            reports.append(json.loads(paths[image + ".packages.json"].read_text()))
            runtimes.append(paths[image + ".source.tar"])
            verify_unique_layer_paths(layout)
            files = installed_inventory(layout)
            verify_directory_aliases(files)
            verify_editor_commands(files)
            if image == "docker-config-engine-trixie":
                data = files.get("run/redis/sonic-db/database_config.json", {})
                validation.require(all(data.get(key) == value for key, value in {
                    "kind": "file", "uid": 0, "gid": 0, "mode": 0o644}.items()),
                    "Common's database configuration has the wrong installed path or ownership")
                for name in ("classid", "pktloc"):
                    validation.require(files.get("etc/libnl-3/" + name, {}).get("kind") == "file",
                                       "libnl runtime configuration is absent: " + name)
            native = verify_source_files(files, reports, elf_machine)
            pairs = verify_symbols(native, runtimes, paths[image + ".debug.tar"], directory)
            config = layout.config
            result = {"_generated": GENERATED_NOTICE, "manifest_digest": layout.descriptor["digest"],
                      "config_digest": layout.manifest["config"]["digest"],
                      "rootfs": config["rootfs"], "config": config.get("config", {}),
                      "source_packages": [item for report in reports for item in report["source_packages"]],
                      "native": native, "debug_pairs": pairs}
            (directory / (image + ".validation.json")).write_text(json.dumps(result, indent=2) + "\n")
            receipt["images"][image] = {"manifest_digest": result["manifest_digest"], "source_elf_count": len(native)}
        receipt["resolution"] = resolution.collect(ROOT, directory, bazel=[args.bazel])
        receipt["status"] = "passed"
    except Exception as error:
        receipt.update(status="failed", error=str(error))
        raise
    finally:
        (directory / "receipt.json").write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
