"""Compile original en_US selections with matching pinned Trixie localedef."""
import io,json,os,re,subprocess,sys,tarfile,tempfile
from pathlib import Path

def main(spec_path,output,audit):
 spec=json.loads(Path(spec_path).read_text());runtime=Path(spec['runtime']).resolve();localedef=Path(spec['localedef']).resolve()
 with tarfile.open(spec['data']) as data,tarfile.open(spec['control']) as controls,tempfile.TemporaryDirectory(dir='.',prefix='vs-locale-') as temp:
  files={m.name.removeprefix('./'):m for m in data};cf={m.name.removeprefix('./'):m for m in controls}
  postinst=controls.extractfile(cf['postinst']).read().decode();supported=data.extractfile(files['usr/share/i18n/SUPPORTED']).read().decode()
  match=re.search(r'cat > \$LG << EOF\n(.*?)\nEOF',postinst,re.S)
  if not match:raise ValueError('unknown locales postinst locale.gen template')
  lines=sorted({line.rstrip() for line in supported.splitlines() if re.match('[a-zA-Z]',line)})
  # Exact fresh postinst (empty selection), then build_debian.sh en_US sed.
  generated=match.group(1)+'\n'+''.join((' '+line if re.match(r'en_US.* ',line) else '# '+line)+'\n' for line in lines)
  selected=[line.split() for line in generated.splitlines() if line.strip() and not line.lstrip().startswith('#')]
  root=Path(temp).resolve();sources=root/'i18n/locales';sources.mkdir(parents=True);charmaps=root/'i18n/charmaps';charmaps.mkdir();prefix=root/'out';(prefix/'usr/lib/locale').mkdir(parents=True)
  aliases=root/'locale.alias';aliases.write_bytes(data.extractfile(files['etc/locale.alias']).read())
  env={'LC_ALL':'C','LANG':'C','TZ':'UTC','PATH':str(runtime/'bin'),'I18NPATH':str(root/'i18n'),'GCONV_PATH':str(runtime/'usr/lib/x86_64-linux-gnu/gconv')}
  pending=[locale.split('.')[0].split('@')[0]+('@'+locale.split('@')[1] if '@' in locale else '') for locale,charset in selected];seen=set()
  while pending:
   name=pending.pop()
   if name in seen:continue
   if '/' in name or name in ('.','..'):raise ValueError('invalid i18n source '+name)
   seen.add(name);body=data.extractfile(files['usr/share/i18n/locales/'+name]).read();(sources/name).write_bytes(body)
   pending.extend(re.findall(rb'(?:copy|include)\s+"([^"/]+)"',body))
   pending=[n.decode() if isinstance(n,bytes) else n for n in pending]
  for charset in sorted({charset for locale,charset in selected}):
   body=data.extractfile(files['usr/share/i18n/charmaps/'+charset+'.gz']).read()
   expanded=subprocess.run([str(runtime/'bin/gzip'),'-dc'],input=body,capture_output=True,env=env,check=True).stdout;(charmaps/charset).write_bytes(expanded)
  commands=[]
  for locale,charset in selected:
   source=locale.split('.')[0].split('@')[0]+('@'+locale.split('@')[1] if '@' in locale else '')
   command=[str(localedef),'--prefix',str(prefix),'-i',str(sources/source),'-c','-f',str(charmaps/charset),'-A',str(aliases),locale]
   done=subprocess.run(command,env=env,capture_output=True,text=True);commands.append({'locale':locale,'charset':charset,'returncode':done.returncode,'stderr':done.stderr})
   if done.returncode or done.stderr:raise RuntimeError('localedef failed '+repr(commands[-1]))
  archive=prefix/'usr/lib/locale/locale-archive'
  listed=subprocess.run([str(localedef),'--prefix',str(prefix),'--list-archive'],env=env,capture_output=True,text=True,check=True).stdout.splitlines()
  with tarfile.open(output,'w',format=tarfile.GNU_FORMAT) as out:
   for name,body in [('usr/lib/locale/locale-archive',archive.read_bytes()),('etc/locale.gen',generated.encode()),('etc/locale.conf',b'#  File generated by update-locale\nLANG=en_US.UTF-8\n')]:
    member=tarfile.TarInfo(name);member.mode=0o644;member.size=len(body);out.addfile(member,io.BytesIO(body))
   link=tarfile.TarInfo('etc/default/locale');link.type=tarfile.SYMTYPE;link.linkname='../locale.conf';link.mode=0o777;out.addfile(link)
   for name,member in files.items():
    if name.startswith('usr/share/i18n/locales/') and member.isfile() and Path(name).name!='en_US':
     whiteout=tarfile.TarInfo(str(Path(name).parent/('.wh.'+Path(name).name)));whiteout.mode=0o644;out.addfile(whiteout)
  Path(audit).write_text(json.dumps({'commands':commands,'archive_locales':listed,'materialized_locale_sources':sorted(seen)},indent=2)+'\n')
if __name__=='__main__':main(*sys.argv[1:])
