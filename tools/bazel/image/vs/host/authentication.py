"""Pure configuration writers ported from current Debian PAM/audit algorithms.

Reference implementation: platform/common/rootfs/postinst/misc/misc.py.
The caller supplies installed profiles, templates and rules; no target binaries run.
"""
import re

def parse_pam_profile(text):
    prof = {}
    field = None
    for line in text.splitlines(keepends=True):
        m = re.match(r'^(\S+):\s+(.*?)\s*$', line, re.S)
        if m:
            field = re.sub(r'-Final$', '', m.group(1))
            if field == 'Conflicts':
                prof['Conflicts'] = set(m.group(2).split(', '))
            else:
                prof[field] = m.group(2)
        else:
            s = line.strip()
            if field is None:
                raise ValueError('pam profile continuation without a field')
            if s:
                prof[field] = prof.get(field, '') + '\n' + s
            prof[field] = prof[field].lstrip('\n \t')
    if prof.get('Session-Interactive-Only') != 'yes':
        for suffix in ('-Type', '', '-Initial'):
            if 'Session' + suffix in prof:
                prof['Session-noninteractive' + suffix] = prof['Session' + suffix]
    return prof


def lines_for(profiles, mod, uctype, pos):
    if pos == 0 and profiles[mod].get(uctype + '-Initial'):
        return profiles[mod][uctype + '-Initial']
    return profiles[mod].get(uctype)


def merge_one_line(line, count):
    m = re.match(r'^((\[[^]]+\]|\w+)\s+\S+)\s*(.*)', line)
    opts = m.group(3).split()
    return m.group(1).replace('end', str(count)) + ' ' + ' '.join(opts) + '\n'


def pam_common(template, profiles, enabled, typ):
    uctype = typ[0].upper() + typ[1:]
    short = typ.replace('-noninteractive', '')
    out = []
    state = 0
    markers = {0: ('# here are the per-package modules (the "Primary" block)', 'Primary'),
               2: ('# and here are more per-package modules (the "Additional" block)', 'Additional')}
    for line in template.splitlines(keepends=True):
        if state == 1:
            if line.startswith("# here's the fallback if no module succeeds"):
                out.append(line)
                state += 1
            continue
        if state == 3:
            if line.startswith('# end of pam-auth-update config'):
                out.append(line)
                state += 1
            continue
        out.append(line)
        if state not in markers or not line.startswith(markers[state][0]):
            continue
        val = markers[state][1]
        mods = [m for m in enabled if profiles[m].get(uctype + '-Type') == val]
        count = sum(len([x for x in re.split(r'\n+', lines_for(profiles, m, uctype, i)) if x])
                    for i, m in enumerate(mods))
        if val == 'Additional':
            count -= 1
        if val == 'Primary' and count == 0:
            out.append('%s\t[default=1]\t\t\tpam_permit.so\n' % short)
        for i, m in enumerate(mods):
            for l in lines_for(profiles, m, uctype, i).split('\n'):
                out.append('%s\t%s' % (short, merge_one_line(l, count)))
                count -= 1
        state += 1
    if state < 4:
        raise ValueError('pam template markers missing for ' + typ)
    saved = []
    prim = [m for m in enabled if profiles[m].get(uctype + '-Type') and profiles[m][uctype + '-Type'] != 'Additional']
    for i, m in enumerate(prim):
        o = lines_for(profiles, m, uctype, i)
        if o:
            saved.append('Module: %s\n%s\n' % (m, o))
    if not prim:
        saved.append('Module: null\n[default=1]\t\t\tpam_permit.so\n')
    add = [m for m in enabled if profiles[m].get(uctype + '-Type') and profiles[m][uctype + '-Type'] != 'Primary']
    for i, m in enumerate(add):
        o = lines_for(profiles, m, uctype, i)
        if o:
            saved.append('Module: %s\n%s\n' % (m, o))
    return ''.join(out), ''.join(saved)



def natural(name):
    return [(0, int(t), '') if t.isdigit() else (1, 0, t) for t in re.findall(r'\d+|\D+', name)]


def augenrules(rules):
    """/usr/sbin/augenrules (audit 3.0.9) over the given rules.d contents."""
    e = d = f = b = ''
    rest = []
    for name in sorted(rules, key=natural):
        for line in rules[name].decode().split('\n')[:-1] if rules[name].endswith(b'\n') else rules[name].decode().split('\n'):
            if not line:
                continue
            if re.match(r'^\s*#', line):
                continue
            if re.match(r'^\s*-e', line):
                e = line
            elif re.match(r'^\s*-D\s*$', line):
                d = line
            elif re.match(r'^\s*-f', line):
                f = line
            elif re.match(r'^\s*-b', line):
                b = line
            else:
                rest.append(line)
    text = '## This file is automatically generated from /etc/audit/rules.d\n%s\n%s\n%s\n' % (d, b, f)
    return (text + ''.join(l + '\n' for l in rest) + e + '\n').encode()



def pam_selection(img, removed):
    profiles = {path.rsplit("/", 1)[1]: parse_pam_profile(data.decode())
                for path, (member, data) in img.files.items()
                if path.startswith("usr/share/pam-configs/") and member.isfile()}
    seen = sorted((name for name in profiles if name not in removed), key=lambda name: (-int(profiles[name]["Priority"]), [-ord(c) for c in name] + [1]))
    enabled = [name for name in seen if profiles[name].get("Default") == "yes"]
    return profiles, seen, enabled


def configure_authentication(img, out, removed, report):
    profiles, seen, enabled = pam_selection(img, removed)
    if profiles:
        for name in enabled:
            if profiles[name].get("Conflicts", set()) & set(enabled):
                raise ValueError("conflicting enabled PAM profiles: " + name)
        for typ in ("auth", "account", "password", "session", "session-noninteractive"):
            common, saved = pam_common(img.read("/usr/share/pam/common-" + typ).decode(), profiles, enabled, typ)
            out.file("/etc/pam.d/common-" + typ, common.encode())
            out.file("/var/lib/pam/" + typ, saved.encode())
        out.file("/var/lib/pam/seen", "".join(name + "\n" for name in seen).encode())
        report["pam"] = {"enabled": enabled, "seen": seen, "removed": removed}
    if not img.exists("/etc/nsswitch.conf") and img.exists("/usr/share/libc-bin/nsswitch.conf"):
        out.file("/etc/nsswitch.conf", img.read("/usr/share/libc-bin/nsswitch.conf"))
    rules = {path.rsplit("/", 1)[1]: data for path, (member, data) in img.files.items()
             if path.startswith("etc/audit/rules.d/") and path.endswith(".rules") and member.isfile()}
    if rules and img.exists("/usr/sbin/augenrules"):
        data = augenrules(rules)
        old = "/etc/audit/audit.rules"
        previous = img.read(old) if img.exists(old) else None
        # auditd configures first; audisp-tacplus later calls augenrules again.
        # Its backup is auditd's generated result, not the packaged input file.
        if img.exists("/var/lib/dpkg/info/audisp-tacplus.postinst") and "audit.rules" in rules:
            previous = augenrules({"audit.rules": rules["audit.rules"]})
        if previous != data:
            if previous is not None:
                out.file(old + ".prev", previous, mode=0o640)
            out.file(old, data, mode=0o640)
        report["audit_rules"] = sorted(rules, key=natural)
