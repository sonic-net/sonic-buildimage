#!/usr/bin/env python3
"""Build source-owned event services and validate native tests and TAR payloads."""
import argparse
import hashlib
import os
import json
import platform
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from tools.bazel.ci.bazel_commands import audit_targets

PREFIX = '//src/sonic-eventd:'
TESTS = [PREFIX + name + '_test' for name in ['eventd', 'eventdb', 'rsyslog_plugin']]
TARS = {
    'eventd-runtime': PREFIX + 'eventd_runtime',
    'eventd-debug': PREFIX + 'eventd_runtime.debug_symbols',
    'rsyslog-runtime': PREFIX + 'rsyslog_plugin_runtime',
    'rsyslog-debug': PREFIX + 'rsyslog_plugin_runtime.debug_symbols',
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bazel', default='bazel')
    parser.add_argument('--bazel-arg', action='append', default=[])
    parser.add_argument('--artifacts', required=True, type=Path)
    parser.add_argument('--architecture', choices=['amd64','arm64'], required=True)
    args = parser.parse_args()
    machine, selected = {'amd64':('x86_64','x86_64_trixie'),'arm64':('aarch64','aarch64_trixie')}[args.architecture]
    if platform.machine() != machine or platform.freedesktop_os_release().get('VERSION_CODENAME') != 'trixie':
        raise ValueError('This job requires native Debian Trixie of the selected architecture')
    output = args.artifacts.resolve(); output.mkdir(parents=True, exist_ok=True)
    options = ['--platforms=@sonic_build_infra//platforms:'+selected,
               '--host_platform=@sonic_build_infra//platforms:'+selected,
               '--jobs=4','--local_resources=cpu=4','--local_resources=memory=7000',*args.bazel_arg]
    audit_targets(args.bazel,options,[*TESTS,*TARS.values()],workspace=ROOT,output=output/'action-audit.json')
    resolution_flags = [value for value in args.bazel_arg if value.startswith(
        ('--override_module=', '--override_repository=', '--registry=', '--repository_cache='))]
    graph = json.loads(subprocess.check_output([args.bazel,'mod','graph',*resolution_flags,'--output=json'],cwd=ROOT,text=True))
    (output/'module-graph.json').write_text(json.dumps(graph,indent=2)+'\n')
    sources = subprocess.check_output([args.bazel,'query',*resolution_flags,
        'labels(srcs, kind("cc_.* rule", //src/sonic-eventd:*))','--output=label'],cwd=ROOT,text=True)
    actual = {line.split(':',1)[1] for line in sources.splitlines() if line.endswith('.cpp')}
    expected = set()
    for path in (ROOT/'src/sonic-eventd').glob('*/subdir.mk'):
        expected.update(name+'.cpp' for name in re.findall(r'\./([^\s]+)\.o',path.read_text()))
    if actual != expected:
        raise ValueError('Bazel/Make C++ source lists differ: '+repr(actual ^ expected))
    subprocess.run([args.bazel,'test',*options,'--nocache_test_results','--test_output=all',
                    '--build_event_json_file='+str(output/'test-events.jsonl'),*TESTS],cwd=ROOT,check=True)
    subprocess.run([args.bazel,'build',*options,*TARS.values()],cwd=ROOT,check=True)
    command = [sys.executable,str(ROOT/'src/sonic-eventd/bazel/verify_packages.py'),
               '--architecture',args.architecture,'--output',str(output/'packages.json')]
    for name,target in TARS.items():
        files = subprocess.check_output([args.bazel,'cquery',*options,'--output=files',target],cwd=ROOT,text=True).splitlines()
        if len(files)!=1: raise ValueError('Expected one TAR output: '+target)
        dest = output/(name+'.tar');shutil.copyfile(ROOT/files[0],dest)
        command += ['--'+name,str(dest)]
    subprocess.run(command,cwd=ROOT,check=True)
    # Archive the resolution state generated by the source build.
    shutil.copyfile(ROOT/'MODULE.bazel.lock', output/'MODULE.bazel.lock')
    (output/'source-coverage.json').write_text(json.dumps({'_generated':{'notice':'AUTO-GENERATED. DO NOT EDIT MANUALLY.','generator':'src/sonic-eventd/bazel/ci.py'},'sources':sorted(actual),'source_sha256':{name:hashlib.sha256((ROOT/'src/sonic-eventd'/name).read_bytes()).hexdigest() for name in sorted(actual)},'checkout_sha':os.environ.get('GITHUB_SHA'),'pr_head_sha':os.environ.get('CI_HEAD_SHA'),'module_sha256':hashlib.sha256((ROOT/'MODULE.bazel').read_bytes()).hexdigest(),'machine':machine,'architecture':args.architecture,'tests':TESTS,'expected_original_test_cases':23,'fixture_parser_regression_cases':2,'expected_total_test_cases':25},indent=2)+'\n')


if __name__=='__main__':
    main()
